# 조건문
# if 기본 구조 - 콜론과 들여쓰끼 (코드 블록)
# 형식:
# if 조건식:
#  실행할 코드 (들여쓰기) -> 자동으로 들여쓰기 적용됨
temp = 85
if temp>80:              # 콜론: 블록 시작 신호
    print("온도 주의")    # 들여쓰기 안 -> 조건 참일 때만 실행
    print("점검 요망")    
print("측정 종료")        # 들여쓰기 끝 -> 조건과 무관하게 항상 실행

# else - 조건이 거짓일 때
